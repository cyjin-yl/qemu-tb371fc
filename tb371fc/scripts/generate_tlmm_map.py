#!/usr/bin/env python3
"""Generate the TB371FC TLMM GPIO tile map from pinned upstream Linux inputs.

Only numeric register offsets are emitted. The native DT confirms the enclosing
window and IRQ; Linux sources supply the tile mapping, not a silicon readback.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path

PIN_SOURCE_SHA256 = "a9f70c0a1e59a076b071492a7fc8c285c9c2c7f1b5a5f1f48099dbb1469cc5a5"
TILES = {"WEST": 0x100000, "SOUTH": 0x500000, "NORTH": 0x900000}
REGEX = re.compile(r"\[(\d+)\]\s*=\s*PINGROUP\((\d+),\s*(WEST|SOUTH|NORTH),")

def parse_groups(text):
    result = {}
    for match in REGEX.finditer(text):
        index, pin, tile = match.groups()
        index, pin = int(index), int(pin)
        if index != pin or index in result or not 0 <= pin < 180:
            raise ValueError("GPIO group indices must be unique, equal and in 0..179")
        result[index] = {"pin": pin, "tile": tile,
                         "offset": TILES[tile] + pin * 0x1000}
    if set(result) != set(range(180)):
        raise ValueError("Expected exactly 180 ordinary GPIO groups")
    if len({v["offset"] for v in result.values()}) != 180:
        raise ValueError("Overlapping GPIO register blocks")
    return [result[i] for i in range(180)]

def render(groups):
    lines = [
        "/* SPDX-License-Identifier: GPL-2.0-or-later */",
        "/* Generated by tb371fc/scripts/generate_tlmm_map.py.",
        " * Linux v6.12.114 drivers/pinctrl/qcom/pinctrl-sm8250.c:",
        " * SHA256 " + PIN_SOURCE_SHA256,
        " * Tile bases: arch/arm64/boot/dts/qcom/sm8250.dtsi.",
        " * These are source-derived offsets, not raw silicon register reads.",
        " */",
        "#ifndef HW_GPIO_QCOM_TB371FC_TLMM_MAP_H",
        "#define HW_GPIO_QCOM_TB371FC_TLMM_MAP_H",
        "",
        "static const uint32_t tlmm_gpio_offsets[QCOM_TB371FC_TLMM_GPIOS] = {",
    ]
    for i in range(0, 180, 6):
        lines.append("    " + " ".join("0x%06x," % g["offset"]
                                      for g in groups[i:i + 6]))
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--linux-source", type=Path, required=True)
    parser.add_argument("--header", type=Path, required=True)
    parser.add_argument("--receipt", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = args.linux_source / "drivers/pinctrl/qcom/pinctrl-sm8250.c"
    dts = args.linux_source / "arch/arm64/boot/dts/qcom/sm8250.dtsi"
    msm = args.linux_source / "drivers/pinctrl/qcom/pinctrl-msm.c"
    data = source.read_bytes()
    if hashlib.sha256(data).hexdigest() != PIN_SOURCE_SHA256:
        raise SystemExit("Unreviewed pinctrl source hash; review before updating the pin map")
    dts_text = dts.read_text()
    for address in ("0x0f100000", "0x0f500000", "0x0f900000"):
        if address not in dts_text:
            raise SystemExit("Expected tile base absent from DTS")
    groups = parse_groups(data.decode())
    output = render(groups)
    receipt = {
        "schema_version": 1,
        "kind": "tlmm-source-derived-map",
        "source_version": "Linux v6.12.114",
        "sources": [
            {"relative_path": str(p.relative_to(args.linux_source)),
             "sha256": hashlib.sha256(p.read_bytes()).hexdigest()}
            for p in (source, dts, msm)
        ],
        "generator_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "header_sha256": hashlib.sha256(output.encode()).hexdigest(),
        "native_window": {"start": 0x0f000000, "size": 0x01000000},
        "native_irq": {"controller": "GIC", "spi": 208, "flags": 4},
        "source_derived_tile_offsets": TILES,
        "ordinary_gpio_count": len(groups),
        "groups": groups,
        "dedicated_ufs_reset": {
            "upstream_group": 180, "ordinary_gpio": False,
            "control_offset": 0x5b8000, "io_offset": 0x5b8004,
            "input_supported": False, "interrupt_supported": False
        },
        "sdc2_control_offset": 0x9b7000,
        "limits": [
            "Source-derived register layout, not a hardware register read.",
            "No measured silicon reset values or analog electrical behavior.",
            "PDC wakeup routing and alternate-function peripherals are separate devices."
        ],
    }
    if args.check:
        if args.header.read_text() != output:
            raise SystemExit("Generated header differs from pinned source")
    else:
        args.header.parent.mkdir(parents=True, exist_ok=True)
        args.header.write_text(output)
        args.receipt.parent.mkdir(parents=True, exist_ok=True)
        args.receipt.write_text(json.dumps(receipt, indent=2, sort_keys=True) + "\n")
    print(json.dumps({"ordinary_gpio_count": len(groups),
                      "header_sha256": receipt["header_sha256"],
                      "checked": args.check}))

if __name__ == "__main__":
    main()
