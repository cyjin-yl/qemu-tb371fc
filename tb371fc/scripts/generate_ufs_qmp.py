#!/usr/bin/env python3
"""Extract the SM8250 QMP UFS software register contract from pinned Linux."""
# SPDX-License-Identifier: GPL-2.0-only
from pathlib import Path
import argparse, hashlib, json, re

def generate(source, output, receipt):
    root = source / "drivers/phy/qualcomm"
    paths = [root / n for n in (
        "phy-qcom-qmp-ufs.c", "phy-qcom-qmp-qserdes-com-v4.h",
        "phy-qcom-qmp-qserdes-txrx-v4.h", "phy-qcom-qmp-pcs-ufs-v4.h")]
    bodies = {p.name: p.read_text() for p in paths}
    definitions = {}
    for p in paths[1:]:
        for name, value in re.findall(r"^#define\s+(\w+)\s+(0x[0-9a-fA-F]+|\d+)\s*$",
                                       bodies[p.name], re.M):
            definitions[name] = int(value, 0)
    entries = {}
    source_c = bodies[paths[0].name]
    groups = [
        ("sm8150_ufsphy_serdes", [0], True),
        ("sm8150_ufsphy_hs_b_serdes", [0], False),
        ("sm8150_ufsphy_tx", [0x400, 0x800], True),
        ("sm8150_ufsphy_rx", [0x600, 0xa00], True),
        ("sm8150_ufsphy_pcs", [0xc00], True),
        ("sm8250_ufsphy_hs_g4_tx", [0x400, 0x800], False),
        ("sm8250_ufsphy_hs_g4_rx", [0x600, 0xa00], False),
        ("sm8150_ufsphy_hs_g4_pcs", [0xc00], False),
    ]
    for name, bases, required in groups:
        match = re.search(r"static const struct qmp_phy_init_tbl " + re.escape(name) +
                          r"\[\]\s*=\s*\{(.*?)\n\};", source_c, re.S)
        if not match:
            raise ValueError("missing exact source table " + name)
        rows = re.findall(r"QMP_PHY_INIT_CFG(?:_LANE)?\((\w+),\s*(0x[0-9a-fA-F]+|\d+)"
                          r"(?:,\s*\d+)?\)", match[1])
        if not rows or match[1].count("QMP_PHY_INIT_CFG") != len(rows):
            raise ValueError("unparsed initializer in " + name)
        for register, value in rows:
            for base in bases:
                address = base + definitions[register]
                e = entries.setdefault(address, {"offset":address, "name":register,
                    "required":False, "documented_driver_values":[], "tables":[]})
                e["required"] |= required
                if int(value, 0) not in e["documented_driver_values"]:
                    e["documented_driver_values"].append(int(value, 0))
                e["tables"].append(name)
    for suffix in ("PHY_START", "POWER_DOWN_CONTROL", "SW_RESET", "READY_STATUS"):
        name = "QPHY_V4_PCS_UFS_" + suffix
        address = 0xc00 + definitions[name]
        entries.setdefault(address, {"offset":address, "name":name,
            "required":False, "documented_driver_values":[], "tables":[]})
    rows = [entries[k] for k in sorted(entries)]
    text = "/* SPDX-License-Identifier: GPL-2.0-only */\n"
    text += "/* Generated by tb371fc/scripts/generate_ufs_qmp.py. */\n"
    text += "static const QcomUfsPhyRegister qcom_ufs_phy_registers[] = {\n"
    for e in rows:
        text += '    { 0x%03x, %s }, /* %s */\n' % (
            e["offset"], "true" if e["required"] else "false", e["name"])
    text += "};\n"
    output.write_text(text)
    receipt.write_text(json.dumps({
        "schema_version":1, "source_version":"Linux 6.12.114",
        "scope":"Documented SM8250 QMP v4 register offsets and programming tables; not silicon POR or analog behavior",
        "sources":[{"path":str(p.relative_to(source)),
                    "sha256":hashlib.sha256(p.read_bytes()).hexdigest()} for p in paths],
        "registers":rows,
        "generated_sha256":hashlib.sha256(output.read_bytes()).hexdigest()
    },indent=2)+"\n")
    print(f"Generated {len(rows)} register entries; {sum(e['required'] for e in rows)} base table registers")

if __name__ == "__main__":
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--linux-source", type=Path, required=True)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--receipt", type=Path, required=True)
    a=p.parse_args()
    generate(a.linux_source,a.output,a.receipt)
